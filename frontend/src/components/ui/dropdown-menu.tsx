        "group/dropdown-menu-item relative flex cursor-pointer items-center gap-2 rounded-md px-2.5 py-2 text-sm text-slate-200 outline-hidden select-none transition-colors duration-150 hover:bg-slate-800/90 hover:text-white focus:bg-blue-600/25 focus:text-white data-[highlighted]:bg-blue-600/25 data-[highlighted]:text-white data-inset:pl-7 data-[variant=destructive]:text-rose-400 data-[variant=destructive]:hover:bg-rose-500/15 data-[variant=destructive]:hover:text-rose-300 data-[variant=destructive]:focus:bg-rose-500/15 data-[variant=destructive]:focus:text-rose-300 data-[variant=destructive]:data-[highlighted]:bg-rose-500/15 data-[variant=destructive]:data-[highlighted]:text-rose-300 data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
